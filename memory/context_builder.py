#!/usr/bin/env python3
"""context_builder.py — compile the canonical fleet_memory DB into the
claude_memory.md prompt (wq#3647). Replaces the hand-edited prose file: the DB
is the source of truth, this regenerates the file deterministically.

Usage:
  context_builder.py                 # write compiled prompt to stdout
  context_builder.py --out PATH      # atomically write to PATH
  context_builder.py --stats         # row counts per table

--out keeps the hand-prose region (HAND_BEGIN..HAND_END) of the existing file
byte-for-byte and appends it after the generated text (wq#4537). Everything
above the region is regenerated; hand prose written there is lost.

wq#4539 phase 1 (one render, one truth): roster and episodes are LIVE reads,
not PG. PG fleet_devices/agent_episodes are frozen (0 writes since 2026-10-08,
audit F4) and wrong for retired nodes PG never learned about (audit F5) — see
`roster()`/`episodes()` below.

wq#4539 phase 2 (wq#4554): decisions and facts are now LIVE reads from
minerva.db too (migrate_decisions.py copied the PG rows over, audited via
`memory_audit`), filtered to non-superseded by the existing `status='active'`
predicate, which phase 0 (QW5) already relies on. PG fleet_facts/fleet_devices/
agent_episodes/fleet_decisions are frozen (renamed retired_*) after this
phase lands — this renderer no longer opens a PG connection at all.
"""
import argparse
import datetime as dt
import os
import re
import sqlite3
import subprocess
import sys
import tempfile

HEADER = """# Claude Extended Memory — Lumen Infrastructure  #GENERATED
# GENERATED by context_builder.py from the fleet_memory PostgreSQL DB (wq#3647)
# at {ts}. DO NOT HAND-EDIT above the hand-prose region at the bottom —
# edits there are overwritten on next regen. Hand prose goes ONLY inside it (wq#4537).
# Roster + episodes: minerva.db (live, wq#4539 phase 1). Decisions: PG fleet_memory.
# Change roster/episode facts via lumen_state.py / lumen_episode.py; decisions via
# the memory-mcp server, then regenerate this file.
# Query live facts: python3 /home/lumen/minerva/lumen_state.py current [subject]

CREDENTIAL RULE: NO literal passwords, tokens, keys, or secrets in this file.
Reference .secrets/ file paths ONLY.
"""

HAND_BEGIN = "<!-- hand-prose:begin -->"
HAND_END = "<!-- hand-prose:end -->"
EMPTY_HAND_PROSE = HAND_BEGIN + """
## HAND PROSE (preserved across regen, wq#4537)

Append prose below this line and above the end marker. This region survives
every context_builder.py regen byte-for-byte; everything above it does not.
Facts go to lumen_state.py ingest, episodes to lumen_episode.py commit.
""" + HAND_END + "\n"

# --- wq#4539 phase 1: live roster from minerva.db state facts --------------
#
# Same "subject.predicate = value (since DATE)" line shape prompt-forge's
# fleet_context.py parses (fleet_context.py:41-44), but fleet_context.py's end
# anchor (`\)\s*$`) requires nothing follow the date. Live lumen_state.py
# output always appends a confidence tag after the date (e.g.
# "(since 2026-10-22)  [UNVERIFIABLE — no probe]") — verified against the live
# fleet on 2026-10-23: 0 of 1244 current-state lines end bare at the date, so
# fleet_context.py's pattern currently matches 0 role lines. This pattern
# drops the end anchor so it still captures subject/predicate/value/since with
# trailing tag text present.
#
# wq#4578 (ruling on wq#4572's contradiction, carried forward from the wq#4553
# phase-1 bundle): with no end anchor, the value group must be GREEDY. A
# non-greedy `.*?` stops at the FIRST "(since YYYY-MM-DD)"-shaped substring on
# the line, so a value whose own free text contains that idiom parsed to a
# truncated value with a stale `since` date and no error. Greedy binds to the
# LAST such clause — the one lumen_state.py actually appends. `.*\S|` keeps the
# group empty-safe (never None) and leaves no trailing whitespace in the value
# without a post-strip. Deliberately NOT re-anchored at end-of-line (even
# tolerating `[tag]`): greedy-vs-non-greedy cannot change WHICH lines match,
# only where the split falls inside a matching line, so this fix carries zero
# risk of repeating fleet_context.py's 0-of-1244 coverage collapse.
LUMEN_STATE_BIN = os.environ.get(
    "LUMEN_STATE_BIN", "/home/lumen/minerva/lumen_state.py")
MINERVA_DB_PATH = os.environ.get(
    "MINERVA_DB_PATH", "/home/lumen/minerva/minerva.db")
STATE_TIMEOUT_S = 20
DB_TIMEOUT_S = 5
EPISODE_LIMIT = 40

_STATE_LINE = re.compile(
    r"^\s*(?P<subject>[\w-]+)\.(?P<predicate>[\w-]+)\s*= (?P<value>.*\S|)\s*"
    r"\(since (?P<since>\d{4}-\d{2}-\d{2})\)")
_RETIRED_RE = re.compile(r"^(retired|decommissioned)\b", re.IGNORECASE)
_ROSTER_PREDICATES = ("role", "status", "tailscale_ip", "lan_ip")


def _run_state_current():
    try:
        proc = subprocess.run(
            ["python3", LUMEN_STATE_BIN, "current"],
            capture_output=True, text=True, timeout=STATE_TIMEOUT_S,
        )
        return proc.stdout if proc.returncode == 0 else ""
    except (OSError, subprocess.TimeoutExpired):
        return ""


def parse_state_lines(text):
    facts = []
    for line in text.splitlines():
        m = _STATE_LINE.match(line)
        if m:
            facts.append(m.groupdict())
    return facts


def _first_sentence(text, limit=220):
    text = text.strip()
    cut = text.split(". ")[0]
    return (cut[:limit - 1] + "…") if len(cut) > limit else cut


def _is_retired(value):
    return bool(value) and bool(_RETIRED_RE.match(value.strip()))


def roster(state_text=None):
    """Live nodes: state subjects with a current `.role` fact, excluding any
    whose role or status fact reads "retired"/"decommissioned" (wq#4541 — PG
    fleet_devices still shows these as available/offline; minerva.db has the
    current RETIRED status). Sorted by hostname for byte-stable renders."""
    text = state_text if state_text is not None else _run_state_current()
    nodes = {}
    for f in parse_state_lines(text):
        if f["predicate"] not in _ROSTER_PREDICATES:
            continue
        nodes.setdefault(f["subject"], {})[f["predicate"]] = f["value"]
    out = []
    for host, node in nodes.items():
        role = node.get("role")
        if not role:
            continue
        if _is_retired(role) or _is_retired(node.get("status")):
            continue
        out.append((host, node))
    return sorted(out, key=lambda t: t[0])


def episodes(db_path=None, limit=EPISODE_LIMIT):
    """Most-recent-N episode digests from minerva.db `archival_notes`
    (wq#1635 writes kind='code-ship'/'session' there via lumen_episode.py).
    Excludes revoked, superseded, and merge-absorbed notes — PG `agent_episodes`
    gets 0 writes (audit F4), so this is the only live episode store."""
    path = db_path or MINERVA_DB_PATH
    try:
        con = sqlite3.connect(f"file:{path}?mode=ro", uri=True, timeout=DB_TIMEOUT_S)
    except sqlite3.Error:
        return []
    try:
        cur = con.execute(
            "SELECT title, source_ref, created_at FROM archival_notes "
            "WHERE kind IN ('code-ship','session') AND revoked_at IS NULL "
            "AND superseded_by IS NULL "
            "AND id NOT IN (SELECT absorbed_id FROM note_merges) "
            "ORDER BY created_at DESC LIMIT ?", (limit,))
        return cur.fetchall()
    except sqlite3.Error:
        return []
    finally:
        con.close()


def hand_prose(path):
    """Return the hand-prose region of the file at path, markers included.

    A missing file or a file without the begin marker yields EMPTY_HAND_PROSE.
    A begin marker with no end marker after it keeps everything to EOF and closes
    the region, so a deleted end marker never costs prose. Any other read error
    propagates: the caller must not replace a file it could not read.
    """
    try:
        with open(path, encoding="utf-8") as fh:
            old = fh.read()
    except FileNotFoundError:
        return EMPTY_HAND_PROSE
    b = old.find(HAND_BEGIN)
    if b < 0:
        return EMPTY_HAND_PROSE
    e = old.find(HAND_END, b)
    if e < 0:
        return old[b:].rstrip("\n") + "\n" + HAND_END + "\n"
    return old[b:e + len(HAND_END)] + "\n"


def _nice_scope(scope):
    return scope.replace("-", " ").replace("_", " ").strip().upper()


def _rationale(rationale, decision):
    """Return a renderable rationale, or '' for empty/provenance-only ones."""
    if not rationale:
        return ""
    r = rationale.strip()
    if not r or r == decision.strip():
        return ""
    if r.startswith("migrated from") or r.startswith("source:"):
        return ""
    return r


def _minerva_connect(db_path=None):
    path = db_path or MINERVA_DB_PATH
    return sqlite3.connect(f"file:{path}?mode=ro", uri=True, timeout=DB_TIMEOUT_S)


def build(conn=None):
    """conn, if given, is a minerva.db sqlite3 connection (tests pass a fixture
    db); defaults to the live minerva.db. wq#4539 phase 2 (wq#4554): decisions
    and facts no longer come from a PG connection — this function takes no PG
    handle at all now."""
    cur = (conn or _minerva_connect()).cursor()
    out = []
    out.append(HEADER.format(ts=dt.datetime.now(dt.timezone.utc)
                             .strftime("%Y-%m-%d %H:%M UTC")))
    out.append("\n---\n")

    # 1. PERMANENT DECISIONS
    cur.execute("""SELECT decision, rationale FROM fleet_decisions
                   WHERE status='active' AND scope='permanent' ORDER BY id""")
    rows = cur.fetchall()
    if rows:
        out.append("## PERMANENT DECISIONS (never re-ask)\n")
        for decision, rationale in rows:
            line = "- " + decision.strip()
            r = _rationale(rationale, decision)
            if r:
                line += "  — " + r
            out.append(line)
        out.append("\n---\n")

    # 2. STANDING RULES (every active decision that is not permanent / frank-correction)
    cur.execute("""SELECT scope, decision, rationale FROM fleet_decisions
                   WHERE status='active' AND scope NOT IN ('permanent','frank-correction')
                   ORDER BY scope, id""")
    rows = cur.fetchall()
    if rows:
        out.append("## STANDING RULES\n")
        cur_scope = None
        for scope, decision, rationale in rows:
            if scope != cur_scope:
                out.append("\n### " + _nice_scope(scope))
                cur_scope = scope
            line = "- " + decision.strip()
            r = _rationale(rationale, decision)
            if r:
                line += " — " + r
            out.append(line)
        out.append("\n---\n")

    # 3. FRANK CORRECTIONS
    cur.execute("""SELECT decision, rationale FROM fleet_decisions
                   WHERE status='active' AND scope='frank-correction' ORDER BY id""")
    rows = cur.fetchall()
    if rows:
        out.append("## FRANK CORRECTIONS\n")
        for i, (decision, rationale) in enumerate(rows, 1):
            line = "%d. %s" % (i, decision.strip())
            r = _rationale(rationale, decision)
            if r:
                line += " — " + r
            out.append(line)
        out.append("\n---\n")

    # 4. FLEET DEVICES (roster) — live minerva.db state facts, wq#4539 phase 1
    rows = roster()
    if rows:
        out.append("## FLEET DEVICES\n")
        out.append("Query `lumen_state.py current <host>` for live detail. Roster snapshot:\n")
        for host, node in rows:
            bits = []
            if node.get("role"):
                bits.append(_first_sentence(node["role"]))
            if node.get("status"):
                bits.append("status=" + _first_sentence(node["status"], limit=120))
            if node.get("tailscale_ip"):
                bits.append("TS " + node["tailscale_ip"].strip())
            if node.get("lan_ip"):
                bits.append("LAN " + node["lan_ip"].strip())
            out.append("- **%s** — %s" % (host, ", ".join(b for b in bits if b)))
        out.append("\n---\n")

    # 5. FLEET FACTS (grouped by subject) — minerva.db, wq#4539 phase 2
    now_iso = dt.datetime.now(dt.timezone.utc).isoformat()
    cur.execute("""SELECT subject, attribute, value, source FROM fleet_facts
                   WHERE status='verified'
                     AND (expires_at IS NULL OR expires_at > ?)
                     AND source LIKE 'claude_memory.md%'
                     AND attribute NOT IN ('ip_tailscale','ip_lan')
                   ORDER BY subject, attribute, id""", (now_iso,))
    rows = cur.fetchall()
    if rows:
        out.append("## FLEET FACTS\n")
        cur_subj = None
        for subject, attribute, value, source in rows:
            if subject != cur_subj:
                out.append("\n### " + subject)
                cur_subj = subject
            val = (value or "").strip()
            out.append("- %s: %s" % (attribute.strip(), val))
        out.append("\n---\n")

    # 6. RECENT EPISODES — minerva.db archival_notes, wq#4539 phase 1
    rows = episodes()
    if rows:
        out.append("## RECENT EPISODES (newest first)\n")
        for title, source_ref, created_at in rows:
            when = (created_at or "")[:10] or "?"
            out.append("- %s — %s" % ((title or source_ref or "?").strip(), when))
        out.append("")

    cur.close()
    return "\n".join(out).rstrip() + "\n"


def stats(conn=None):
    cur = (conn or _minerva_connect()).cursor()
    lines = []
    for t in ("fleet_facts", "fleet_decisions"):
        cur.execute("SELECT count(*) FROM " + t)
        lines.append("%-16s %d" % (t, cur.fetchone()[0]))
    cur.close()
    lines.append("%-16s %d" % ("roster(live)", len(roster())))
    lines.append("%-16s %d" % ("episodes(live)", len(episodes())))
    return "\n".join(lines)


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("--out")
    ap.add_argument("--stats", action="store_true")
    args = ap.parse_args()
    conn = _minerva_connect()
    try:
        if args.stats:
            print(stats(conn))
            return
        text = build(conn)
    finally:
        conn.close()
    if args.out:
        text += "\n" + hand_prose(args.out)
        d = os.path.dirname(os.path.abspath(args.out))
        fd, tmp = tempfile.mkstemp(dir=d, prefix=".ctxbuild-")
        with os.fdopen(fd, "w", encoding="utf-8") as fh:
            fh.write(text)
        os.replace(tmp, args.out)
        sys.stderr.write("wrote %d bytes to %s\n" % (len(text), args.out))
    else:
        sys.stdout.write(text)


if __name__ == "__main__":
    main()
